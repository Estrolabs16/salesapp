import 'package:cloud_firestore/cloud_firestore.dart';

DateTime? dateFromValue(Object? value) {
  if (value is Timestamp) return value.toDate();
  if (value is DateTime) return value;
  if (value is String) return DateTime.tryParse(value);
  return null;
}

DateTime dateOrNow(Object? value) => dateFromValue(value) ?? DateTime.now();

double doubleFromValue(Object? value) {
  if (value is num) return value.toDouble();
  if (value is String) return double.tryParse(value) ?? 0;
  return 0;
}

int intFromValue(Object? value) {
  if (value is num) return value.toInt();
  if (value is String) return int.tryParse(value) ?? 0;
  return 0;
}

String stringFromValue(Object? value) => value is String ? value : '';
